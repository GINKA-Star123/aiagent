def clean_text(text: str) -> str:
    return " ".join(text.strip().split())


def make_record(instruction: str, output: str, input_text: str = "") -> dict:
    return {
        "instruction": clean_text(instruction),
        "input": input_text,
        "output": clean_text(output),
        "history": [],
    }


class DatasetBuilder:
    def __init__(self) -> None:
        self.instructions: set[str] = set()
        self.outputs: set[str] = set()

    def add(self, bucket: list[dict], instruction: str, output: str, input_text: str = "") -> None:
        instruction = clean_text(instruction)
        output = clean_text(output)
        if not instruction or not output:
            return
        if any(fragment in instruction for fragment in BAD_INSTRUCTION_FRAGMENTS):
            raise ValueError(f"polluted instruction: {instruction}")
        if instruction in self.instructions or output in self.outputs:
            return
        self.instructions.add(instruction)
        self.outputs.add(output)
        bucket.append(make_record(instruction, output, input_text))


