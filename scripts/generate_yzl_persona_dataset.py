def trim_or_fail(name: str, bucket: list[dict], count: int) -> list[dict]:
    if len(bucket) < count:
        raise RuntimeError(f"{name} not enough records: {len(bucket)} < {count}")
    return bucket[:count]


records = trim_or_fail("core", core, CORE_COUNT)
records += trim_or_fail("daily", daily, DAILY_COUNT)
records += trim_or_fail("tasks", tasks, TASK_COUNT)

if len(records) != TARGET_COUNT:
    raise RuntimeError(f"bad record count: {len(records)}")

for record in records:
    instruction = record["instruction"]
    if any(fragment in instruction for fragment in BAD_INSTRUCTION_FRAGMENTS):
        raise RuntimeError(f"polluted instruction: {instruction}")

